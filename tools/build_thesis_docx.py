def manuscript_markdown() -> str:
    cn, en, symbols = split_frontmatter()
    cn_block = "\n\n".join(
        [
            styled("AbstractTitle", TITLE_CN),
            cn.replace(
                "鞅 Hardy–Orlicz 空间",
                "**摘要：**鞅 Hardy–Orlicz 空间",
                1,
            ),
            "图 0 幅，表 2 个，参考文献 23 篇",
            "**关键词：**鞅 Hardy–Orlicz 空间；Young 函数；对偶空间；平方函数；条件平方函数；"
            "\\(K^\\Psi\\) 空间  \n**分类号：**O211.6；O177.2",
        ]
    )
    # Remove duplicated keyword line from the source fragment.
    cn_block = re.sub(r"\n\n\*\*关键词：\*\*.*?(?=\n\n图 0 幅)", "", cn_block, flags=re.S)

    en_block = "\n\n".join(
        [
            styled("AbstractTitle", TITLE_EN),
            en.replace(
                "Martingale Hardy–Orlicz spaces",
                "**Abstract:** Martingale Hardy–Orlicz spaces",
                1,
            ),
            "**Keywords:** martingale Hardy–Orlicz space; Young function; dual space; square function; "
            "conditional square function; \\(K^\\Psi\\) space  \n"
            "**Classification:** O211.6; O177.2",
        ]
    )
    en_block = re.sub(r"\n\n\*\*Keywords:\*\*.*?(?=\n\n\*\*Keywords:\*\*)", "", en_block, flags=re.S)

    body_files = [
        "01-introduction.md",
        "02-preliminaries.md",
        "03-duality.md",
        "04-relations.md",
        "05-conclusion.md",
    ]
    body = "\n\n".join(read(name) for name in body_files)
    endmatter = read("06-achievements-acknowledgments.md")
    parts = [
        cover_markdown(),
        cn_block,
        raw_page_break(),
        en_block,
        raw_page_break(),
        "[[CSU_TOC]]",
        raw_page_break(),
        "# 符号说明\n\n" + symbols,
        raw_section_break(roman=True),
        body,
        clean_references(),
        endmatter,
    ]
    return "\n\n".join(parts)


def set_font(style, *, cn: str, en: str, size: float, bold: bool | None = None) -> None:
    style.font.name = en
    style.font.size = Pt(size)
    if bold is not None:
        style.font.bold = bold
    style.element.rPr.rFonts.set(qn("w:eastAsia"), cn)


