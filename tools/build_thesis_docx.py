def set_repeat_table_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    tbl_header.set(qn("w:val"), "true")
    tr_pr.append(tbl_header)


def set_cell_border(cell, **edges) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = tc_pr.first_child_found_in("w:tcBorders")
    if tc_borders is None:
        tc_borders = OxmlElement("w:tcBorders")
        tc_pr.append(tc_borders)
    for edge in ("top", "bottom", "left", "right", "insideH", "insideV"):
        if edge not in edges:
            continue
        tag = f"w:{edge}"
        element = tc_borders.find(qn(tag))
        if element is None:
            element = OxmlElement(tag)
            tc_borders.append(element)
        for key, value in edges[edge].items():
            element.set(qn(f"w:{key}"), str(value))


def apply_three_line_table(table) -> None:
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    no_line = {"val": "nil"}
    top_bottom = {"val": "single", "sz": "12", "color": "000000"}
    mid = {"val": "single", "sz": "6", "color": "000000"}
    for r_idx, row in enumerate(table.rows):
        for cell in row.cells:
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            edges = {"left": no_line, "right": no_line, "insideV": no_line}
            if r_idx == 0:
                edges.update({"top": top_bottom, "bottom": mid})
            elif r_idx == len(table.rows) - 1:
                edges.update({"bottom": top_bottom})
            set_cell_border(cell, **edges)
            for p in cell.paragraphs:
                p.paragraph_format.first_line_indent = Pt(0)
                p.paragraph_format.line_spacing = 1
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                for run in p.runs:
                    run.font.size = Pt(10.5)
                    run.font.name = "Times New Roman"
                    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "宋体")
    if table.rows:
        set_repeat_table_header(table.rows[0])


def add_field(paragraph, instruction: str, placeholder: str = "") -> None:
    run = paragraph.add_run()
    fld_char = OxmlElement("w:fldChar")
    fld_char.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = instruction
    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    text = OxmlElement("w:t")
    text.text = placeholder
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.extend([fld_char, instr, separate, text, end])


def set_page_numbering(section, fmt: str, start: int = 1) -> None:
    sect_pr = section._sectPr
    pg_num = sect_pr.find(qn("w:pgNumType"))
    if pg_num is None:
        pg_num = OxmlElement("w:pgNumType")
        sect_pr.append(pg_num)
    pg_num.set(qn("w:fmt"), fmt)
    pg_num.set(qn("w:start"), str(start))


def add_page_footer(section) -> None:
    section.footer.is_linked_to_previous = False
    paragraph = section.footer.paragraphs[0]
    paragraph.clear()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_field(paragraph, "PAGE", "1")
    for run in paragraph.runs:
        run.font.name = "Times New Roman"
        run.font.size = Pt(9)


def add_body_header(section) -> None:
    section.header.is_linked_to_previous = False
    header = section.header
    for paragraph in header.paragraphs:
        paragraph.clear()
    table = header.add_table(rows=1, cols=2, width=Cm(14.6))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.columns[0].width = Cm(7.3)
    table.columns[1].width = Cm(7.3)
    left = table.cell(0, 0).paragraphs[0]
    left.text = "中南大学硕士学位论文"
    left.alignment = WD_ALIGN_PARAGRAPH.LEFT
    right = table.cell(0, 1).paragraphs[0]
    right.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    add_field(right, 'STYLEREF "Heading 1"', "第1章 绪论")
    for cell in table.rows[0].cells:
        set_cell_border(cell, bottom={"val": "single", "sz": "6", "color": "000000"})
        for p in cell.paragraphs:
            p.paragraph_format.first_line_indent = Pt(0)
            for run in p.runs:
                run.font.name = "Times New Roman"
                run.font.size = Pt(9)
                run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "宋体")


def replace_toc_marker(doc: Document) -> None:
    for paragraph in doc.paragraphs:
        if paragraph.text.strip() != "[[CSU_TOC]]":
            continue
        paragraph.clear()
        paragraph.text = "目　录"
        paragraph.style = doc.styles["TOCHeading"]
        toc_xml = OxmlElement("w:p")
        paragraph._p.addnext(toc_xml)
        toc_p = Paragraph(toc_xml, paragraph._parent)
        toc_p.paragraph_format.first_line_indent = Pt(0)
        add_field(toc_p, r'TOC \o "1-2" \h \z \u', "打开 Word 后右键更新目录")
        break


def polish_document(doc: Document) -> None:
    # Update fields when Word opens the document.
    settings = doc.settings._element
    update_fields = settings.find(qn("w:updateFields"))
    if update_fields is None:
        update_fields = OxmlElement("w:updateFields")
        settings.append(update_fields)
    update_fields.set(qn("w:val"), "true")

    replace_toc_marker(doc)

    for paragraph in doc.paragraphs:
        fmt = paragraph.paragraph_format
        if paragraph.style.name in {"Normal", "Body Text", "First Paragraph"}:
            fmt.line_spacing_rule = WD_LINE_SPACING.EXACTLY
            fmt.line_spacing = Pt(20)
            fmt.space_after = Pt(0)
            if paragraph.text.strip():
                fmt.first_line_indent = Pt(24)
        if paragraph._p.xpath(".//m:oMath | .//m:oMathPara"):
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            fmt.first_line_indent = Pt(0)
        if paragraph.text.startswith("[") and re.match(r"^\[\d+\]", paragraph.text):
            fmt.first_line_indent = Pt(-24)
            fmt.left_indent = Pt(24)
        for run in paragraph.runs:
            run.font.name = "Times New Roman"
            run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "宋体")

    for table in doc.tables:
        apply_three_line_table(table)

    sections = doc.sections
    if len(sections) < 3:
        raise RuntimeError(f"Expected at least 3 Word sections, found {len(sections)}")

    # Section 0: cover, title page and declarations; no header or page number.
    sections[0].header.is_linked_to_previous = False
    sections[0].footer.is_linked_to_previous = False
    for p in sections[0].header.paragraphs + sections[0].footer.paragraphs:
        p.clear()

    # Section 1: abstracts, TOC and symbols, lower-case Roman page numbers.
    sections[1].header.is_linked_to_previous = False
    for p in sections[1].header.paragraphs:
        p.clear()
    set_page_numbering(sections[1], "lowerRoman", 1)
    add_page_footer(sections[1])

    # Last section: body and all back matter, Arabic page numbers and running header.
    body_section = sections[-1]
    set_page_numbering(body_section, "decimal", 1)
    add_page_footer(body_section)
    add_body_header(body_section)


def build() -> Path:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        reference = tmp_path / "reference.docx"
        source = tmp_path / "thesis.md"
        generated = tmp_path / "generated.docx"
        configure_reference_doc(reference)
        source.write_text(manuscript_markdown(), encoding="utf-8")
        pypandoc.convert_file(
            str(source),
            "docx",
            outputfile=str(generated),
            extra_args=[
                f"--reference-doc={reference}",
                "--from=markdown+raw_attribute+raw_tex+tex_math_single_backslash",
                "--standalone",
            ],
        )
        doc = Document(generated)
        polish_document(doc)
        doc.core_properties.title = TITLE_CN
        doc.core_properties.subject = "中南大学硕士学位论文修订稿"
        doc.core_properties.author = "杜闻伦"
        doc.core_properties.keywords = "鞅 Hardy–Orlicz 空间; Young 函数; 对偶空间"
        doc.save(OUT)
    return OUT


