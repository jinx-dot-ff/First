def read(name: str) -> str:
    return (SRC / name).read_text(encoding="utf-8")


def raw_page_break() -> str:
    return """```{=openxml}
<w:p><w:r><w:br w:type="page"/></w:r></w:p>
```"""


def raw_section_break(*, roman: bool = False) -> str:
    pg_num = '<w:pgNumType w:fmt="lowerRoman" w:start="1"/>' if roman else ""
    return f"""```{{=openxml}}
<w:p><w:pPr><w:sectPr>
<w:type w:val="nextPage"/>
<w:pgSz w:w="{PAGE_W}" w:h="{PAGE_H}"/>
<w:pgMar w:top="{MARGIN_TOP}" w:right="{MARGIN_SIDE}" w:bottom="{MARGIN_BOTTOM}" w:left="{MARGIN_SIDE}" w:header="{HEADER}" w:footer="{FOOTER}" w:gutter="0"/>
{pg_num}
</w:sectPr></w:pPr></w:p>
```"""


def styled(style: str, text: str) -> str:
    return f'::: {{custom-style="{style}"}}\n{text}\n:::'


def split_frontmatter() -> tuple[str, str, str]:
    text = read("00-frontmatter.md")
    cn, rest = text.split("# Abstract", 1)
    en, symbols = rest.split("# 符号说明", 1)
    cn = cn.replace("# 中文摘要", "", 1).strip()
    en = en.strip()
    symbols = symbols.strip()
    return cn, en, symbols


def clean_references() -> str:
    lines = read("references.md").splitlines()
    out: list[str] = ["# 参考文献"]
    for line in lines[1:]:
        if line.startswith("## "):
            if line.startswith("## 六、"):
                break
            continue
        if line.startswith(">"):
            continue
        match = re.match(r"^(\d+)\.\s+(.*)$", line)
        if match:
            out.append(f'[{match.group(1)}] {match.group(2)}')
        else:
            out.append(line)
    return "\n".join(out).strip()


